def _clean_name(value):
    text = unicodedata.normalize('NFKC', str(value or ''))
    text = text.replace('&', ' and ')
    text = text.replace('’', "'")
    text = re.sub(r'[^A-Za-zА-Яа-я0-9\s\-]', ' ', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text


